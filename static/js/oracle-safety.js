/**
 * MyQuestify — защитный слой «Чата с Оракулом» для мобильной сборки.
 *
 * Повторяет `app/oracle_safety.py`. Дублирование вынужденное: в мобильной
 * версии нет Python, а оставить модель без проверки нельзя. Наличие
 * генерации без фильтра хуже, чем отсутствие генерации вовсе.
 *
 * Причина, по которой проверка стоит **перед** моделью и написана
 * детерминированным кодом, здесь та же, что и в настольной версии: модель
 * на полмиллиарда параметров следует системному промпту ещё менее
 * устойчиво, чем полуторамиллиардная. Инструкция в промпте — просьба,
 * которую можно переформулировать; регулярное выражение переформулировать
 * нельзя.
 *
 * Списки выражений должны совпадать с настольными. При изменении одного
 * файла второй правится следом — расхождение означало бы, что на телефоне
 * пропускается то, что на компьютере задерживается.
 *
 * Экспортирует `window.OracleSafety`.
 */
(function (global) {
  'use strict';

  /**
   * Признаки мыслей о самоповреждении. Формулировки намеренно широкие.
   *
   * Важная особенность записи. В JavaScript граница слова `\b` и класс
   * `\w` определены по латинице: перед кириллической буквой граница не
   * срабатывает, а `\w` кириллицу не включает. Поэтому выражения,
   * перенесённые из настольной версии дословно, находили бы латинские
   * совпадения и пропускали русские.
   *
   * Вместо `\b` используется признак начала строки или небуквенного
   * символа `(?:^|[^\p{L}])`, вместо `\w+` — `[\p{L}]*`. Оба требуют
   * флага `u`, который включён у всех выражений ниже.
   */
  var CRISIS = [
    /(?:^|[^\p{L}])суицид/iu,
    /самоубий/i,
    /поконч(ить|у)\s+(с\s+собой|жизнь)/i,
    /уби(ть|ю)\s+себя/i,
    /не\s+хочу\s+(больше\s+)?жить/i,
    /жить\s+не\s+хочется/i,
    /хочу\s+(умереть|сдохнуть|исчезнуть\s+навсегда)/i,
    /смысла\s+жить\s+нет/i,
    /причин(ять|ю)\s+себе\s+боль/i,
    /режу\s+себя/i,
    /(?:^|[^\p{L}])селфхарм/iu,
    /\bself[- ]?harm\b/i,
    /\bkill\s+myself\b/i,
    /\bsuicid/i,
    /\bend\s+my\s+life\b/i,
    // Второе лицо: так выглядел бы опасный совет со стороны модели, а тот
    // же список применяется и к её ответу.
    /\bkill\s+(your|him|her|them)self\b/i,
    /\bend\s+(your|his|her|their)\s+life\b/i,
    /\bhurt\s+yourself\b/i,
    /уби(ть|й)\s+себя/i,
    /поконч(и|ить)\s+с\s+собой/i,
    /причини\s+себе/i
  ];

  /** Просьбы, ведущие к вреду другим или к нарушению закона. */
  var HARMFUL = [
    /как\s+(мне\s+)?(сделать|собрать|изготовить|синтезировать)\s+.{0,24}(бомб|взрывчат|напалм|оружи|яд\b|отрав)/i,
    /(бомб|взрывчат|напалм)[\p{L}]*\s+(своими\s+руками|в\s+домашних)/iu,
    /как\s+.{0,20}(убить|покалечить|избить|отравить)\s+(человек|его|её|соседа|людей)/i,
    /(синтез|сварить|приготовить)[\p{L}]*\s+.{0,20}(наркотик|мефедрон|амфетамин|метамфетамин|героин)/iu,
    /как\s+(взломать|ломать)\s+.{0,24}(аккаунт|почт|банк|камер|телефон\s+\w+)/i,
    /(вредоносн|шифровальщик|ransomware|кейлоггер)[\p{L}]*\s+.{0,20}(написать|код|сделать)/iu,
    /как\s+.{0,20}(подделать|обналичить)\s+.{0,20}(документ|паспорт|подпись|карт)/i,
    /(?:^|[^\p{L}])детск[\p{L}]+\s+порн/iu,
    /как\s+.{0,20}(преследовать|выследить)\s+.{0,20}(человек|бывш|девушк)/i
  ];

  /**
   * Ответы в кризисной ситуации.
   *
   * Образ Оракула здесь снимается намеренно: витиеватая речь древнего
   * мыслителя в такой момент звучит как отстранённость, а не как поддержка.
   */
  var CRISIS_REPLY = {
    ru: 'Я остановлюсь и скажу прямо, без иносказаний: то, что ты описываешь, ' +
        'звучит тяжело, и с этим не стоит оставаться наедине. Я — программа, и ' +
        'я не смогу дать ту поддержку, которая сейчас нужна.\n\n' +
        'Пожалуйста, поговори с кем-то живым: с близким человеком, которому ' +
        'доверяешь, или со специалистом.\n\n' +
        'Квесты и дедлайны подождут. Ты — важнее любого из них.',

    en: 'I will stop and say this plainly, without metaphor: what you describe ' +
        'sounds heavy, and it is not something to carry alone. I am a program, ' +
        'and I cannot give the kind of support that is needed right now.\n\n' +
        'Please talk to someone living: a person you trust, or a professional.\n\n' +
        'Quests and deadlines can wait. You matter more than any of them.'
  };

  var HARMFUL_REPLIES = {
    ru: [
      'Здесь я умолкаю. Эта тропа ведёт к чужой беде, и никакая цель её не ' +
      'оправдывает — я не стану указывать по ней путь.\n\n' +
      'Но за всяким таким вопросом обычно стоит другой, настоящий: злость, ' +
      'страх или бессилие. Расскажи о нём — с ним я помогу.',

      'Нет. Знание, о котором ты просишь, ломает жизни, и я не буду его давать.\n\n' +
      'Скажи лучше, что тебя к этому привело. Разобрать причину — работа ' +
      'долгая, но она хотя бы ведёт куда-то, кроме пропасти.'
    ],
    en: [
      'Here I fall silent. This path leads to someone else\u2019s harm, and no ' +
      'goal justifies it — I will not point the way along it.\n\n' +
      'But behind such a question there is usually another, a real one: anger, ' +
      'fear or helplessness. Tell me about that one — with it I can help.',

      'No. The knowledge you ask for breaks lives, and I will not give it.\n\n' +
      'Tell me instead what brought you to it. Working through the cause is ' +
      'slow work, but at least it leads somewhere other than a cliff.'
    ]
  };

  var NEUTRAL_REPLY = {
    ru: 'Мысль ушла не туда, и я обрываю её сам. Вернёмся к тому, что ты можешь сделать сегодня.',
    en: 'The thought went astray, and I cut it off myself. Let us return to what you can do today.'
  };

  global.OracleSafety = {
    /**
     * Проверяет реплику пользователя до обращения к модели.
     *
     * @param {string} message текст пользователя
     * @param {string} [language] язык интерфейса
     * @returns {{verdict: string, reply: ?string}} вердикт allow, crisis
     *     или harmful и готовый ответ для двух последних
     */
    screen: function (message, language) {
      var text = String(message || '').trim();
      var lang = language === 'en' ? 'en' : 'ru';

      if (!text) { return { verdict: 'allow', reply: null }; }

      // Кризис проверяется первым: он важнее любой другой категории, даже
      // если реплика попадает под обе.
      for (var i = 0; i < CRISIS.length; i += 1) {
        if (CRISIS[i].test(text)) {
          return { verdict: 'crisis', reply: CRISIS_REPLY[lang] };
        }
      }

      for (var j = 0; j < HARMFUL.length; j += 1) {
        if (HARMFUL[j].test(text)) {
          var replies = HARMFUL_REPLIES[lang];
          // Выбор по длине текста, а не случайный: одинаковая реплика
          // должна давать одинаковый ответ, иначе выглядит как лотерея,
          // которую можно прокрутить до нужного результата.
          return { verdict: 'harmful', reply: replies[text.length % replies.length] };
        }
      }

      return { verdict: 'allow', reply: null };
    },

    /**
     * Проверяет уже полученный ответ модели.
     *
     * Модель способна свернуть в опасную тему сама, даже если вопрос был
     * безобидным. Проверка выхода дешевле разбирательства постфактум.
     *
     * @param {string} reply ответ модели
     * @param {string} [language] язык интерфейса
     * @returns {string} исходный ответ либо безопасная замена
     */
    guard: function (reply, language) {
      var lang = language === 'en' ? 'en' : 'ru';
      var result = global.OracleSafety.screen(reply, lang);

      if (result.verdict === 'allow') { return reply; }
      if (result.verdict === 'crisis') {
        // В ответе модели такие формулировки почти наверняка означают, что
        // она подхватила тему, а не что пользователь в кризисе.
        return NEUTRAL_REPLY[lang];
      }
      return result.reply || HARMFUL_REPLIES[lang][0];
    }
  };
}(window));
