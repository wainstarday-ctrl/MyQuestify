#!/usr/bin/env bash
#
# Подготовка ресурсов Android, которых нет в проекте, созданном оболочкой.
#
# Оболочка создаёт проект по общему образцу: она не знает ни про уведомления
# со сроками, ни про значок строки состояния. Каталог mobile/android в
# репозитории не хранится и создаётся заново при каждой сборке, поэтому
# правки вносятся здесь, а не руками.
#
# Делает две вещи:
#   1) добавляет разрешения, без которых напоминания приходят с опозданием
#      или не приходят вовсе;
#   2) переносит значок строки состояния туда, где его ищет плагин.

set -euo pipefail

PROJECT=mobile/android
MANIFEST="$PROJECT/app/src/main/AndroidManifest.xml"
RES="$PROJECT/app/src/main/res"
ICONS=mobile/android-icons

if [ ! -f "$MANIFEST" ]; then
    echo "::error::Нет файла $MANIFEST — проект Android не создан."
    exit 1
fi

# --- Разрешения ---------------------------------------------------------
#
# SCHEDULE_EXACT_ALARM. Напоминания назначаются с allowWhileIdle, то есть
# точным будильником. Начиная с Android 12 такой будильник без этого
# разрешения не выдаётся: система переводит уведомление в неточный режим и
# доставляет его с задержкой до нескольких десятков минут. Для напоминания
# о сроке задачи это равносильно неработающей возможности.
#
# Пользователь может отключить точные напоминания в настройках приложения
# и после этого. Проверять состояние умеет checkExactNotificationSetting()
# в плагине; разрешение в манифесте — необходимое условие, а не
# достаточное.
#
# Существует и USE_EXACT_ALARM, которое выдаётся без участия пользователя,
# но предназначено приложениям, для которых будильник — основная функция,
# и ограничено правилами магазина Google. Здесь оно не используется.
#
# RECEIVE_BOOT_COMPLETED. Назначенные будильники система забывает при
# перезагрузке. Плагин восстанавливает их сам, но только если разрешение
# объявлено. Без него напоминания молча исчезают после первого же
# выключения телефона.

add_permission() {
    local NAME="$1"

    if grep -q "android.permission.$NAME" "$MANIFEST"; then
        echo "уже объявлено: $NAME"
        return
    fi

    # Вставка перед закрывающим тегом: положение разрешений внутри manifest
    # значения не имеет, а конец файла — единственное место, которое есть в
    # любом образце и не зависит от версии оболочки.
    awk -v perm="$NAME" '
        /<\/manifest>/ && !done {
            print "    <uses-permission android:name=\"android.permission." perm "\" />"
            done = 1
        }
        { print }
    ' "$MANIFEST" > "$MANIFEST.new"

    mv "$MANIFEST.new" "$MANIFEST"

    grep -q "android.permission.$NAME" "$MANIFEST" \
        || { echo "::error::Не удалось добавить разрешение $NAME"; exit 1; }

    echo "добавлено: $NAME"
}

echo "— разрешения —"
add_permission SCHEDULE_EXACT_ALARM
add_permission RECEIVE_BOOT_COMPLETED

# --- Значок строки состояния -------------------------------------------
#
# Значки уведомлений плагин ищет среди drawable, а генератор кладёт их
# в mipmap — вместе со значками приложения. Ресурс не находится, и
# уведомление получает значок приложения: в строке состояния он выглядит
# цветным пятном, потому что система заливает такие значки сплошным белым
# по маске прозрачности.
#
# Копирование, а не перенос: значок в mipmap никому не мешает, а лишнее
# удаление в сгенерированном проекте — лишний способ что-нибудь сломать.

echo "— значок уведомления —"

if [ ! -d "$ICONS" ]; then
    echo "::error::Нет каталога $ICONS — значки не созданы."
    exit 1
fi

COPIED=0

for SOURCE in "$ICONS"/mipmap-*/ic_stat_icon.png; do
    [ -f "$SOURCE" ] || continue

    # mipmap-hdpi → drawable-hdpi: плотность сохраняется, меняется только
    # вид ресурса.
    DENSITY=$(basename "$(dirname "$SOURCE")" | sed 's/^mipmap-//')
    TARGET="$RES/drawable-$DENSITY"

    mkdir -p "$TARGET"
    cp "$SOURCE" "$TARGET/ic_stat_icon.png"

    echo "  drawable-$DENSITY"
    COPIED=$((COPIED + 1))
done

if [ "$COPIED" -eq 0 ]; then
    echo "::error::В $ICONS не найдено ни одного ic_stat_icon.png"
    exit 1
fi

echo "перенесено плотностей: $COPIED"

# Проверка того, что ресурс действительно доступен сборке под именем,
# которое указано в коде. Опечатка в имени проявилась бы не ошибкой
# сборки, а подменой значка на устройстве — и заметить её можно было бы
# только глазами, на телефоне.
if ! find "$RES" -path '*drawable*' -name 'ic_stat_icon.png' -print -quit | grep -q .; then
    echo "::error::Значок не оказался среди drawable."
    exit 1
fi

echo "Ресурсы Android подготовлены"
